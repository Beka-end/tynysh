-- Пакет на знакомство: 10 сообщений вместо 20.
-- Потолок Plus: 5 сообщений в день вместо 10.
--
-- Что это меняет в деньгах (при цене 3,26 ₸ за сообщение подписчика):
--   предельный расход Plus был 978 ₸ в месяц при подписке 990 ₸ — почти впритык.
--   Стало 489 ₸, то есть даже самый активный подписчик оставляет 501 ₸.
--   Заодно снова сходится годовой тариф, если решишь его вернуть.
--   Бесплатный пакет обходится примерно в 27 ₸ на человека вместо 55 ₸.

update app_settings
   set value = 10,
       note = 'Сколько сообщений Досу даётся бесплатно ВСЕГО, не в сутки'
 where key = 'dos_free_total';

update app_settings
   set value = 5,
       note = 'Сколько сообщений в день у Plus (0 — совсем без потолка)'
 where key = 'dos_plus_daily';
